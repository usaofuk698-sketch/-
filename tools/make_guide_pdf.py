def mq5_defaults() -> dict[str, str]:
    """Read ``input <type> Name = value;`` defaults straight from the EA."""
    src = MQ5.read_text()
    pattern = re.compile(r"^\s*input\s+(?:double|int|long|bool)\s+(\w+)\s*=\s*([-\w.]+)\s*;", re.M)
    return {name: value for name, value in pattern.findall(src)}


